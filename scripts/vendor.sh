#!/usr/bin/env bash
# Generates vendor/: the HTTP/1.1 protocol layer (src/Std/Http/Protocol) of the upstream client
# stack, leanprover/lean4 PRs 14546-14548 at the head of 14548, renamed from Std.Http.Protocol to
# LeanHttpProto.Http.Protocol so that it cannot collide with the copy in the toolchain.
#
# Only the protocol layer is copied.  It keeps using the toolchain's Std.Http data types (Request,
# Response, Headers, ...), so the library's public API stays on Std.Http's types; the two helpers
# the copied layer needs from the stack's data layer are in LeanHttp/VendorCompat.lean.  NOTES.md
# says why the copy is needed at all.
#
# vendor/ is generated, ignored by Git, and must not be committed.  Delete it when the toolchain
# ships these changes.
#
# Usage: scripts/vendor.sh [<lean4 clone that has the commit below>]
#   The clone defaults to $LEAN4_CLONE, then ~/prog/oss/lean4.
#   e.g. git -C <clone> fetch https://github.com/leanprover/lean4 pull/14548/head
commit=3e6f42a58a955f7fd9a6df4213f3be4bb68e3e3b
clone=${1:-${LEAN4_CLONE:-$HOME/prog/oss/lean4}}
here=$(cd "$(dirname "$0")/.." && pwd) || exit 1
out=$here/vendor
dest=$out/LeanHttpProto/Http

git -C "$clone" cat-file -e "$commit^{commit}" || { echo "vendor.sh: $clone lacks $commit" >&2; exit 1; }
tmp=$(mktemp --directory) || exit 1
trap 'rm --recursive --force "$tmp"' EXIT
# File by file rather than with `git archive`: in a partial clone (blobs fetched on demand, as CI
# makes one) this fetches only these files, where `git archive` fetched about 100 MB.
git -C "$clone" ls-tree -r -z "$commit" -- src/Std/Http/Protocol > "$tmp/files" || exit 1
while IFS= read -r -d '' entry; do
  meta=${entry%%$'\t'*}
  path=${entry#*$'\t'}
  case $meta in
    *" blob "*) ;;
    *) echo "vendor.sh: not a file: $entry" >&2; exit 1 ;;
  esac
  mkdir --parents "$tmp/$(dirname "$path")" || exit 1
  git -C "$clone" cat-file blob "${meta##* }" > "$tmp/$path" || exit 1
done < "$tmp/files"
[ -f "$tmp/src/Std/Http/Protocol/H1.lean" ] || { echo "vendor.sh: no H1.lean at $commit" >&2; exit 1; }

rm --recursive --force "$out" || exit 1
mkdir --parents "$dest" || exit 1
cp --recursive "$tmp/src/Std/Http/Protocol" "$dest/" || exit 1

# - rename the modules and namespaces;
# - drop `prelude`, which only core may use;
# - after each `namespace`, open Std.Http so that the data types (Status, Headers, ...) still resolve;
# - give H1.lean the two data-layer helpers the stack added (Status.isInterim,
#   Method.anticipatesContent).
find "$dest" -name '*.lean' -print0 \
  | xargs --null sed --in-place --regexp-extended \
      -e 's/\bStd\.Http\.Protocol\b/LeanHttpProto.Http.Protocol/g' \
      -e '/^prelude$/d' \
      -e 's/^(namespace LeanHttpProto\.Http\.Protocol.*)$/\1\nopen Std.Http/' || exit 1
sed --in-place -e 's/^public import Std\.Http\.Data$/public import Std.Http.Data\npublic import LeanHttp.VendorCompat/' \
  "$dest/Protocol/H1.lean" || exit 1
grep --quiet --fixed-strings 'import LeanHttp.VendorCompat' "$dest/Protocol/H1.lean" \
  || { echo "vendor.sh: could not add the Compat import to H1.lean" >&2; exit 1; }
if grep --recursive --quiet 'Std\.Http\.Protocol' "$dest"; then
  echo "vendor.sh: references to Std.Http.Protocol remain" >&2; exit 1
fi

printf 'leanprover/lean4 %s src/Std/Http/Protocol, generated by scripts/vendor.sh\n' "$commit" \
  > "$out/SOURCE" || exit 1
echo "vendored $commit into $out"
